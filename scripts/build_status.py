#!/usr/bin/env python3
"""Regenerate docs/STATUS.md and the status table inside README.md.

The table is built from docs/rfd_index.json and each package's rfd.toml, so it cannot drift from
what is actually in the repository. RFDs without a package are listed as "not started".

Usage:
    python scripts/build_status.py          # rewrite the files
    python scripts/build_status.py --check  # exit 1 if they are out of date (used in CI)
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "aisecurity_rfds"
TESTS = ROOT / "tests"
INDEX = json.loads((ROOT / "docs" / "rfd_index.json").read_text())
BEGIN = "<!-- STATUS:BEGIN -->"
END = "<!-- STATUS:END -->"
KINDS = ("reference-implementation", "simulation", "analysis")


def count_tests(test_dir: Path) -> int:
    if not test_dir.is_dir():
        return 0
    n = 0
    for f in test_dir.rglob("test_*.py"):
        for node in ast.walk(ast.parse(f.read_text())):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test_"):
                n += 1
    return n


def collect() -> list[dict]:
    rows = []
    for entry in INDEX:
        pkg = next(iter(sorted(SRC.glob(f"rfd_{entry['number']:03d}_*"))), None)
        row = {**entry, "present": pkg is not None, "kind": None, "summary": "", "tests": 0,
               "addressed": None, "total": None}
        if pkg is not None and (pkg / "rfd.toml").is_file():
            meta = tomllib.loads((pkg / "rfd.toml").read_text())
            row.update(
                kind=meta.get("kind"),
                summary=meta.get("summary", ""),
                addressed=meta.get("open_questions_addressed"),
                total=meta.get("open_questions_total"),
                tests=count_tests(TESTS / pkg.name),
            )
        rows.append(row)
    return rows


def render(rows: list[dict]) -> str:
    present = [r for r in rows if r["present"]]
    by_kind = {k: sum(1 for r in present if r["kind"] == k) for k in KINDS}
    breakdown = ", ".join(f"{n} {k}" for k, n in by_kind.items() if n)
    head = f"**{len(present)} of {len(rows)} RFD packages present**"
    if present:
        head += (f" ({breakdown}); {sum(r['tests'] for r in present)} RFD-specific test functions "
                 "(parametrised cases are not expanded, so pytest runs more).")
    else:
        head += "."
    lines = [
        head,
        "",
        "| # | RFD | Author | Kind | Open questions addressed | Test functions | What the package provides |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        if r["present"]:
            oq = f"{r['addressed']}/{r['total']}" if r["total"] is not None else "-"
            summary = str(r["summary"]).replace("|", "\\|").replace("\n", " ")
            lines.append(
                f"| {r['number']:03d} | {r['title']} | {r['author']} | {r['kind']} | {oq} | {r['tests']} | {summary} |"
            )
        else:
            lines.append(f"| {r['number']:03d} | {r['title']} | {r['author']} | not started | - | - | |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    table = render(collect())
    status_md = (
        "# Status of the 42 RFD packages\n\n"
        "Generated by `scripts/build_status.py` from `docs/rfd_index.json` and each package's `rfd.toml`. "
        "Do not edit by hand.\n\n" + table
    )
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text()
    if BEGIN not in readme or END not in readme:
        print("README.md is missing the status markers", file=sys.stderr)
        return 2
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new_readme = f"{head}{BEGIN}\n{table}{END}{tail}"
    status_path = ROOT / "docs" / "STATUS.md"

    if args.check:
        ok = status_path.exists() and status_path.read_text() == status_md and readme == new_readme
        if not ok:
            print("docs/STATUS.md or the README status table is out of date; run scripts/build_status.py",
                  file=sys.stderr)
        return 0 if ok else 1

    status_path.write_text(status_md)
    readme_path.write_text(new_readme)
    print(table.splitlines()[0])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
